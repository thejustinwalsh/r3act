import assert from 'node:assert/strict';
import {openBrowser} from 'vitexec/cli';
import {writeFile} from 'node:fs/promises';
const browser=await openBrowser({gpu:false});
const errors=[];
try{
 const context=await browser.newContext({ignoreHTTPSErrors:true,viewport:{width:1440,height:1100}});
 const page=await context.newPage();
 page.on('pageerror',error=>errors.push(error.message));
 page.on('console',msg=>{if(msg.type()==='error')errors.push(msg.text());});
 await page.goto('https://async-transition-stress.localhost:1355/native-root-queue.html',{waitUntil:'networkidle'});
 const snapshot=()=>page.evaluate(()=>window.__nativeRootQueueDemoDiagnostics.snapshot());
 const initial=await snapshot();
 const main=page.getByRole('textbox',{name:'Main editable draft',exact:true});
 const fork=page.getByRole('textbox',{name:'Fork editable draft',exact:true});
 await main.fill('Keep this main draft');await fork.fill('Keep this fork draft');
 await page.evaluate(()=>{window.__mainInput=document.querySelector('[aria-label="Main editable draft"]');window.__forkInput=document.querySelector('[aria-label="Fork editable draft"]');});
 await page.getByRole('button',{name:'Start overlapping batch'}).click();
 await page.getByRole('button',{name:'Urgent +1',exact:true}).first().click();
 await main.focus();
 await page.waitForFunction(()=>document.querySelector('[aria-label="Main committed value"]')?.textContent==='1');
 const pending=await snapshot();
 assert.equal(pending.activeResourceTimers,3);
 await page.waitForFunction(()=>document.querySelector('[aria-label="Main committed value"]')?.textContent==='1001');
 const fast=await snapshot();
 assert.equal(await main.inputValue(),'Keep this main draft');
 assert.equal(await fork.inputValue(),'Keep this fork draft');
 assert.ok(await page.evaluate(()=>window.__mainInput===document.querySelector('[aria-label="Main editable draft"]')&&window.__forkInput===document.querySelector('[aria-label="Fork editable draft"]')));
 assert.ok(await page.evaluate(()=>document.activeElement===window.__mainInput),'Transition stole focus');
 await page.waitForFunction(()=>document.querySelector('[aria-label="Fork-owned committed value"]')?.textContent==='10');
 const forkReady=await snapshot();
 assert.equal(await page.locator('[aria-label="Main committed value"]').textContent(),'1001');
 await page.waitForFunction(()=>document.querySelector('[aria-label="Main committed value"]')?.textContent==='1101');
 assert.equal(await page.locator('[aria-label="Fork committed value"]').textContent(),'1101');
 const settled=await snapshot();
 assert.equal(settled.activeResourceTimers,0);
 await page.screenshot({path:'.cache/native-root-queue-milestone/desktop.png',fullPage:true});
 await page.getByRole('button',{name:'Start overlapping batch'}).click();
 const slower=page.locator('article.operation').filter({hasText:'Shared group · slower resource'}).last();
 await slower.getByRole('button',{name:'Cancel wait',exact:true}).click();
 await page.waitForFunction(()=>[...document.querySelectorAll('.operation-status')].some(n=>n.textContent.includes('Cancelled')));
 const cancelled=await snapshot();
 const canceledElapsed=cancelled.operations.find(op=>op.status==='cancelled').elapsedMs;
 await page.waitForTimeout(180);
 assert.equal((await snapshot()).operations.find(op=>op.status==='cancelled').elapsedMs,canceledElapsed,'Canceled timer progress kept advancing');
 await page.waitForFunction(()=>document.querySelector('[aria-label="Main committed value"]')?.textContent==='2201');
 await page.waitForFunction(()=>document.querySelector('[aria-label="Fork-owned committed value"]')?.textContent==='20');
 assert.equal(await main.inputValue(),'Keep this main draft');
 await page.getByRole('button',{name:'Start overlapping batch'}).click();
 await page.evaluate(()=>{window.__oldQueueFacade=window.__nativeRootQueueDemoDiagnostics;window.dispatchEvent(new Event('pagehide'));});
 const disposed=await page.evaluate(()=>window.__oldQueueFacade.snapshot());
 assert.equal(disposed.disposed,true);
 assert.equal(disposed.mainRoot.ownerCount,0);assert.equal(disposed.forkRoot.ownerCount,0);
 assert.equal(disposed.activeResourceTimers,0);assert.equal(disposed.clockTimerActive,false);
 assert.equal(disposed.store.roots,0);assert.equal(disposed.forkStore.roots,0);
 await page.waitForTimeout(150);
 assert.equal(errors.length,0,errors.join('\n'));
 const mobile=await context.newPage();
 await mobile.setViewportSize({width:390,height:844});
 await mobile.goto('https://async-transition-stress.localhost:1355/native-root-queue.html',{waitUntil:'networkidle'});
 assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'Mobile horizontal overflow');
 await mobile.screenshot({path:'.cache/native-root-queue-milestone/mobile.png',fullPage:true});
 await mobile.evaluate(()=>window.dispatchEvent(new Event('pagehide')));
 await writeFile('.cache/native-root-queue-milestone/browser-result.json',JSON.stringify({status:'PASS',initial,pending,fast,forkReady,settled,cancelled,disposed,errors},null,2));
 console.log('PASS browser native queue: 3 overlapping timed scopes, urgent +1, reverse shared publications, fork-owned isolation, draft/node/focus preservation, cancel wait retained action, pending teardown, mobile no overflow.');
}finally{await browser.close();}
