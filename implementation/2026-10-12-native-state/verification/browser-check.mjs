import assert from 'node:assert/strict';
import {openBrowser,run} from 'vitexec/cli';
import {writeFile} from 'node:fs/promises';
const browser=await openBrowser({gpu:false});
const errors=[];
try {
 const context=await browser.newContext({ignoreHTTPSErrors:true,viewport:{width:1280,height:1050}});
 const page=await context.newPage();
 page.on('pageerror',e=>errors.push(e.message));
 page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
 await page.goto('https://async-transition-stress.localhost:1355/native-state-props.html',{waitUntil:'networkidle'});
 await page.getByRole('button',{name:'Pause effect',exact:true}).waitFor();
 await run(page,`console.log('ready', JSON.stringify(globalThis.__nativeStateDemoDiagnostics.snapshot()))`,{onLog:console.log});
 const observe=()=>page.evaluate(()=>({x:document.querySelector('.orb').getAttribute('data-x'),diag:globalThis.__nativeStateDemoDiagnostics.snapshot(),counters:JSON.parse(document.querySelector('#diagnostics').textContent)}));
 const start=await observe();
 await page.waitForFunction(x=>document.querySelector('.orb').getAttribute('data-x')!==x,start.x);
 const after=await observe();
 assert.equal(after.diag.sourceValueSyncVisits,start.diag.sourceValueSyncVisits,'RAF scanned component cache');
 await page.getByRole('button',{name:'Pause effect',exact:true}).click();
 await page.getByRole('button',{name:'Resume effect',exact:true}).waitFor();
 const paused=await observe();
 await page.waitForTimeout(100);
 assert.equal((await observe()).x,paused.x,'Effect kept running after deactivation');
 await page.getByRole('button',{name:'Nudge right',exact:true}).click();
 await page.waitForFunction(x=>document.querySelector('.orb').getAttribute('data-x')===String((Number(x)+18)%250),paused.x);
 const alpha=page.getByRole('textbox',{name:'Edit alpha',exact:true});
 await alpha.fill('A retained draft');
 await page.evaluate(()=>{window.__alphaNode=document.querySelector('[aria-label="Edit alpha"]');});
 await page.getByRole('button',{name:'Reorder keys',exact:true}).click();
 assert.equal(await alpha.inputValue(),'A retained draft');
 assert.ok(await page.evaluate(()=>window.__alphaNode===document.querySelector('[aria-label="Edit alpha"]')),'Key reorder replaced input');
 await page.getByRole('button',{name:'Remove rows',exact:true}).click();
 await alpha.waitFor({state:'detached'});
 await page.getByRole('button',{name:'Mount rows',exact:true}).click();
 assert.equal(await alpha.inputValue(),'Alpha draft');
 await page.getByRole('button',{name:'Change message',exact:true}).click();
 await page.getByRole('button',{name:'Toggle branch',exact:true}).click();
 await page.getByText('State branch is visible: Updated.').waitFor();
 await page.getByRole('button',{name:'Resume effect',exact:true}).click();
 const resumed=await observe();
 await page.waitForFunction(x=>document.querySelector('.orb').getAttribute('data-x')!==x,resumed.x);
 assert.equal(errors.length,0,errors.join('\n'));
 await page.screenshot({path:'.cache/native-state-milestone/browser.png',fullPage:true});
 await writeFile('.cache/native-state-milestone/browser-result.json',JSON.stringify({status:'PASS',url:page.url(),start,after,paused,final:await observe(),errors},null,2));
 await page.evaluate(()=>window.dispatchEvent(new Event('pagehide')));
 assert.equal(await page.locator('#app .demo-root').count(),0,'pagehide retained host tree');
 assert.equal(await page.evaluate(()=>!!window.__nativeStateDemoDiagnostics),false,'pagehide retained facade');
 console.log('Native TSX browser contracts PASS');
}finally{await browser.close();}
